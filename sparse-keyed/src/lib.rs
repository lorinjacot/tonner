/// An entry in the dense vector of a [`PrimaryMap`] or a [`SecondaryMap`]. Contains the value of the entry and its associated key.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct DenseEntry<T> {
    /// The value of the entry.
    pub value: T,

    /// The key associated with the entry.
    pub key: Key,
}

